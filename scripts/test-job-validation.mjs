import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const html=readFileSync('public/job-management.html','utf8');
const start=html.indexOf('function validJob(j){');
const end=html.indexOf('async function saveEditor()',start);
assert.ok(start>=0&&end>start);
const F={invoiceAmount:{value:'100'},paid:{value:'20'}};
const context={F,jobs:[],editingIndex:-1,Number,URL,normalize:v=>String(v).toLowerCase().replace(/[^a-z0-9]+/g,' ').trim(),stage:j=>j.currentDepartment==='PRODUCTION'?'production':'orders'};
vm.createContext(context);
vm.runInContext(html.slice(start,end)+';globalThis.testValidation=validJob;',context);
const base={jobsheetFiles:'KZ-101',customer:'Company X',item:'Jersey',orderDate:'2026-10-14',currentDepartment:'SALES',deliveryTime:'2026-10-20',jobMeta:{quantity:'',sizeBreakdown:'',artworkApproved:'',artworkLink:''}};
const validate=j=>context.testValidation(j);
assert.equal(validate(base),'');
assert.match(validate({...base,customer:''}),/CUSTOMER/);
assert.match(validate({...base,orderDate:''}),/ORDER DATE/);
assert.match(validate({...base,currentDepartment:'PRODUCTION'}),/approved artwork/);
assert.equal(validate({...base,currentDepartment:'PRODUCTION',jobMeta:{quantity:'30',sizeBreakdown:'M-10, L-20',artworkApproved:'yes',artworkLink:'https://example.com/artwork'}}),'');
context.jobs=[{...base,currentDepartment:'PRODUCTION'}];context.editingIndex=0;
assert.equal(validate({...base,currentDepartment:'PRODUCTION'}),'','Existing production job can be edited without retroactive blocking');
console.log('PASS: Required fields, Production entry gate, legacy production-job editing');
