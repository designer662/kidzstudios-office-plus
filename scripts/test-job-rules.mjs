import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={TextEncoder,window:{},globalThis:null};
vm.runInNewContext(readFileSync('public/job-rules.js','utf8'),context);
const rules=context.window.KSJobs;
assert.equal(rules.stage({currentDepartment:'SALES'}),'orders');
assert.equal(rules.stage({currentDepartment:'DESIGN'}),'artwork');
assert.equal(rules.stage({currentDepartment:'PRODUCTION QC'}),'production');
assert.equal(rules.stage({currentDepartment:'CLOSED'}),'completed');
assert.equal(rules.stage({currentDepartment:'UNKNOWN'}),'unmapped');
assert.equal(rules.stage({}),'orders');
assert.equal(rules.validateUniqueRefs([{jobsheetFiles:'KS-001'},{jobsheetFiles:'KS-002'}]),'');
assert.match(rules.validateUniqueRefs([{jobsheetFiles:'KS-001'},{jobsheetFiles:'ks 001'}]),/Duplicate/i);
assert.match(rules.validateUniqueRefs([{jobsheetFiles:''}]),/needs/i);
assert.equal(rules.payloadSize({a:'J'.repeat(500)}),508);
const large=Array.from({length:501},(_,i)=>({jobsheetFiles:`TEST-${i}`}));
assert.equal(rules.validateUniqueRefs(large),'');
console.log('PASS: Shared job stage classification, unique references, 501-record validation and size calculation');
