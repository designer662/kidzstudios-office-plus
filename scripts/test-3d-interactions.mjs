import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const code=readFileSync('public/office-3d.js','utf8');
assert.match(code,/new ei\(\.66,\.76,3\.04,12\)/,'character selection collider enlarged');
assert.match(code,/intersectObjects\(st,!1\)/,'real 3D geometry raycast retained');
assert.match(code,/Mt\.project\(o\)/,'screen-space character selection fallback exists');
assert.match(code,/Math\.hypot\(L\.clientX-Ut\.x,L\.clientY-Ut\.y\)>6/,'dragging must not select workers');
assert.match(code,/markCharacterSelection\?\.\(\)/,'3D selection signals click-away handler');
const marker='const sceneWheel=L=>';
const at=code.indexOf(marker);
assert.ok(at!==-1,'wheel handler installed');
const end=code.indexOf(';\nr.domElement.addEventListener("wheel",sceneWheel',at);
assert.ok(end>at,'wheel zoom capture registration present');
const functionSrc=code.slice(at,end+1);
const sandbox={it:1.14,F:{},Hn:{clamp:(x,a,b)=>Math.max(a,Math.min(b,x))}};
vm.runInNewContext(functionSrc+'\nthis.sceneWheel=sceneWheel;',sandbox);
let prevented=0,intercepted=0;
const evt=deltaY=>({cancelable:true,deltaY,deltaMode:0,preventDefault(){prevented++},stopImmediatePropagation(){intercepted++}});
sandbox.sceneWheel(evt(-300));assert.ok(sandbox.it>1.14,'scroll up zooms in');
sandbox.sceneWheel(evt(300));assert.ok(Math.abs(sandbox.it-1.14)<0.002,'scroll down zooms out');
assert.equal(prevented,2);assert.equal(intercepted,2);
assert.match(code,/addEventListener\("wheel",sceneWheel,\{capture:!0,passive:!1\}\)/,'wheel handler captures before OrbitControls');
assert.match(code,/removeEventListener\("wheel",sceneWheel,!0\)/,'wheel handler disposed correctly');
console.log('PASS 3D controls: larger click colliders, fallback hit test, pointerup selection coordination, wheel in/out, event capture and cleanup.');
