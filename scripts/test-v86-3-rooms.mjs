import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const html=read('public/index.html'),three=read('public/office-3d.js'),scene=read('source/src/office-scene.ts'),character=read('source/src/office-character.ts');
for(const room of ['showroom','store','surau','toilets','pantry','workspace'])assert.ok(html.includes(`<option value="${room}">`),`Room option ${room}`);
assert.match(html,/id="ksRoomJump"/);
assert.match(html,/office-v86-3-polish.css/);
assert.match(html,/office-room-nav.js/);
assert.match(html,/selectRoom:id=>/);
assert.match(three,/ks:3d-ready/);
assert.match(read('public/office-quality.js'),/ks:3d-ready/);
assert.match(three,/focusRoom\(L\)/,'Compiled 3D must expose the room focus API');
assert.match(scene,/focusRoom\(id\)/,'Source 3D must preserve room focus after rebuild');
assert.match(character,/if\(isFemale\)[\s\S]*const cloth=shade\(shirt/,'3D character source must keep hijab in rebuilds');
assert.match(three,/if\(y\)\{let H=Xe\(T,\.92\)/,'Shipped 3D includes hijab mesh');
assert.match(three,/t\.action==="coffee"\?1-u:0/,'Cup animation requires coffee action');
const actions=[];
const picker={value:'store',listeners:new Map(),addEventListener(name,fn){this.listeners.set(name,fn)}};
const ctx={document:{getElementById:id=>id==='ksRoomJump'?picker:null},window:{OfficeSuite:{selectRoom:id=>actions.push(['office',id])},office3d:{focusRoom:id=>actions.push(['3d',id])}}};
vm.runInNewContext(read('public/office-room-nav.js'),ctx,{filename:'office-room-nav.js'});
picker.listeners.get('change')();
assert.deepEqual(actions,[['office','store'],['3d','store']]);
assert.equal(picker.value,'','Picker must reset after room selection');
picker.value='surau';picker.listeners.get('change')();
assert.deepEqual(actions.slice(2),[['office','surau'],['3d','surau']]);
const quality=read('public/office-quality.js');
const qualityPicker={value:'balanced',addEventListener(){}};
const timers=[];const mockWindow={office3d:{setQuality(v){actions.push(['quality',v])}},addEventListener(){}};
vm.runInNewContext(quality,{document:{getElementById:id=>id==='ksVisualQuality'?qualityPicker:null},window:mockWindow,localStorage:{getItem:()=>null},matchMedia:()=>({matches:true}),setInterval:()=>{throw Error('Already ready; should not poll')}});
assert.equal(qualityPicker.value,'eco','First-load mobile should default to Eco');
assert.deepEqual(actions.at(-1),['quality','eco']);
console.log('PASS V86.3 room picker, 3D focus, source/bundle hijab, privacy-safe animation and responsive quality');
